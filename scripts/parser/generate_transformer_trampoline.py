def generate_transform_result_types(rule_types, additional_result_types):
    result_types = sorted({info.cpp_type for info in rule_types.values()}.union(additional_result_types))
    lines = []
    for cpp_type in result_types:
        stable_name = json.dumps(f"duckdb.transform_result.{cpp_type}")
        lines.append(f"DUCKDB_REGISTER_TRANSFORM_RESULT_TYPE({stable_name}, {cpp_type});\n")
    return "".join(lines)


def main():
    arg_parser = argparse.ArgumentParser(description="Generate trampoline-style transformer wrappers.")
    arg_parser.add_argument("--write", action="store_true", help="Write generated files to disk.")
    arg_parser.add_argument(
        "--report",
        action="store_true",
        help="Print per-rule trampoline generation status.",
    )
    arg_parser.add_argument(
        "--grammar",
        action="append",
        default=None,
        help="Grammar file to process for reports/previews. Defaults to all statement grammar files.",
    )
    args = arg_parser.parse_args()

    all_grammar_files = discover_grammar_files()
    grammar_files = sorted(set(args.grammar or all_grammar_files))
    rules = load_grammar_rules(grammar_files)
    all_rules = load_grammar_rules(all_grammar_files)
    config_file = type_dir / "transformer_trampoline.yml"
    rule_config = load_transformer_trampoline_config(config_file, all_rules.keys())
    grammar_types_file = type_dir / "grammar_types.yml"
    rule_types, excluded_rules = load_grammar_types(grammar_types_file)
    matcher_override_config = load_matcher_rule_overrides(grammar_types_file)
    matcher_overrides = load_matcher_overrides(grammar_types_file)

    emitter = UseGramPreviewEmitter(rules, rule_types, excluded_rules, matcher_overrides, rule_config)
    emitter.validate_grammar_types()
    if args.write:
        if args.grammar is not None:
            arg_parser.error("--write always generates all statement grammar files")
        additional_result_types = load_additional_transform_result_types(grammar_types_file)
        result_types = generate_transform_result_types(rule_types, additional_result_types)
        write_hpp(emitter.emit_header_declarations(), result_types)
        write_cpp(emitter.emit_source())
        write_matcher_rule_overrides(matcher_override_config)
        packrat_rules = load_packrat_memoized_rules(grammar_types_file, all_rules.keys())
        collapsible_rules = load_collapsible_rules(grammar_types_file, emitter.emitted_ops_rules())
        write_packrat_memoized_rules(packrat_rules)
        write_rule_labels(load_rule_labels(grammar_types_file, all_rules.keys()))
        write_collapsible_rules(collapsible_rules)
        write_expression_depth_rules(*load_expression_depth_rules(grammar_types_file, all_rules.keys()))
        write_rule_ids(all_rules)
    elif args.report:
        print(f"grammar files: {', '.join(grammar_files)}")
        print(emitter.emit_report())
    else:
        print(f"// grammar files: {', '.join(grammar_files)}")
        print(f"// rules: {len(rules)}")
        print(emitter.emit())


