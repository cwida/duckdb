class ManualTransformRegistry:
    def __init__(self, paths):
        self.signatures = {}
        self.declarations = {}
        self._load(sorted(paths))

    @staticmethod
    def _signature_start(text, match_start):
        line_start = text.rfind("\n", 0, match_start) + 1
        if text[line_start:match_start].strip():
            return line_start
        previous_line_end = line_start - 1
        while previous_line_end > 0:
            previous_line_start = text.rfind("\n", 0, previous_line_end) + 1
            if text[previous_line_start:previous_line_end].strip():
                return previous_line_start
            previous_line_end = previous_line_start - 1
        return 0

    def _load(self, paths):
        pattern = re.compile(r"\bPEGTransformerFactory::Transform([A-Za-z0-9_]+)\s*\(")
        for path in paths:
            text = path.read_text()
            for match in pattern.finditer(text):
                paren_start = text.index("(", match.start())
                depth = 0
                paren_end = None
                for offset, char in enumerate(text[paren_start:]):
                    if char == "(":
                        depth += 1
                    elif char == ")":
                        depth -= 1
                        if depth == 0:
                            paren_end = paren_start + offset
                            break
                if paren_end is None:
                    continue
                next_token = text[paren_end + 1 :].lstrip()
                if not next_token.startswith("{"):
                    continue
                signature_start = self._signature_start(text, match.start())
                signature = text[signature_start : paren_end + 1].strip()
                rule_name = match.group(1)
                self.signatures.setdefault(rule_name, set()).add(self._signature_key(signature))
                declaration = signature.replace("PEGTransformerFactory::", "", 1)
                declaration = "\tstatic " + declaration.replace("\n", "\n\t") + ";\n"
                self.declarations.setdefault(rule_name, []).append(declaration)

    @staticmethod
    def _signature_key(signature):
        prefix = "PEGTransformerFactory::"
        signature = norm_ws(signature)
        if prefix in signature:
            return signature[signature.find(prefix) :]
        return signature

    def has_rule(self, rule_name):
        return rule_name in self.signatures

    def has_no_arg_rule(self, rule_name):
        pattern = re.compile(rf"^PEGTransformerFactory::Transform{re.escape(rule_name)}\(PEGTransformer\s*&\s*\w+\)$")
        return any(pattern.match(signature) for signature in self.signatures.get(rule_name, ()))

    def has_parse_result_rule(self, rule_name):
        pattern = re.compile(
            rf"^PEGTransformerFactory::Transform{re.escape(rule_name)}"
            rf"\(PEGTransformer\s*&\s*\w+,\s*(?:const\s+)?ParseResult\s*&\s*\w+\)$"
        )
        return any(pattern.match(signature) for signature in self.signatures.get(rule_name, ()))

    def get_declarations(self, rule_name):
        return self.declarations.get(rule_name, ())


